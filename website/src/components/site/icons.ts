/** One SVG path of unit squares for a bitmap. */
export function bitmapPath(rows: readonly string[]) {
  const pixels: string[] = [];
  for (let y = 0; y < rows.length; y++) {
    const row = rows[y]!;
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '#') pixels.push(`M${x} ${y}h1v1h-1z`);
    }
  }
  return pixels.join('');
}
